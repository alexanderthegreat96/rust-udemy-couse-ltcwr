#![allow(unused_variables)]
fn main() {
    // signed integers
    // i8, i32 and i16
    // can store both negative and positive values
    let some_var: i32 = -112;

    // unsigned integers
    // can store only positive values
    // as a result, they have more memory to work with
    // therefore the values can be much larger

    let another_var: u32 = 25884884;

    // delimiting integers using underscore
    let one_million: u32 = 1_000_000;
}
